# sri.py — Sleep Regularity Index (SRI)
#
# Computes SRI from optional GGIR CK counts or the backwards-compatible SVM
# input. GGIR R is used for reference tests, not required at runtime.
#
# SRI measures the probability that any two epochs 24 hours apart share the same
# sleep/wake state, rescaled to a percentage:
#
#     SRI = 100  -> perfectly regular (state at time t always equals state at t+24h)
#     SRI = 0    -> no better than chance
#     SRI = -100 -> perfectly irregular (state always flips 24h later)
#
# Reference:
#   Phillips A.J.K. et al. (2017). Irregular sleep/wake patterns are associated
#   with poorer academic performance and delayed circadian and sleep/wake timing.
#   Scientific Reports, 7, 3216.
#   Formula as summarised in Fischer et al. (2021), PMC8503839:
#
#            -100 + 200/(M(N-1)) * sum_{j=1}^{M} sum_{i=1}^{N-1} delta(s_{i,j}, s_{i+1,j})
#
#   where  s_{i,j} in {0 (sleep), 1 (wake)} is the state at epoch j on day i,
#          M = epochs per day, N = number of days, and
#          delta(a, b) = 1 if a == b else 0.
#
# NOTE ON RELATION TO OTHER METRICS:
#   SRI is NOT a function of M10 / L5 and shares no inputs with them.
#   M10 / L5 describe the amplitude and timing of the *average* activity day
#   (continuous SVM, collapsed across days). SRI describes day-to-day
#   *reproducibility* of the *binary* sleep/wake state. SRI is the close cousin
#   of Interdaily Stability (IS) — both quantify regularity — but IS compares
#   each day to the grand-average profile using continuous activity, whereas SRI
#   compares each day to the *next* day using binary states.

import warnings
import numpy as np
import pandas as pd
from ck_input import counts_to_minutes, regular_grid, timed_series


# ── Sleep/wake classification ───────────────────────────────────────────────────

# Cole-Kripke (1992) automatic sleep/wake scoring for 1-minute epochs.
#   D_t = P * ( 106*A_{t-4} + 54*A_{t-3} + 58*A_{t-2} + 76*A_{t-1}
#             + 230*A_t + 74*A_{t+1} + 67*A_{t+2} )
#   epoch t is scored SLEEP if D_t < 1, otherwise WAKE.
# See: Cole R.J., Kripke D.F., Gruen W., Mullaney D.J., Gillin J.C. (1992).
#   Automatic sleep/wake identification from wrist activity. Sleep, 15(5), 461-469.
_CK_WEIGHTS   = np.array([106, 54, 58, 76, 230, 74, 67], dtype=float)  # A-4 .. A+2
_CK_OFFSETS   = np.array([-4, -3, -2, -1, 0, 1, 2])
_CK_SCALE     = 0.001   # the "P" scale factor in the original formula
_CK_THRESHOLD = 1.0     # D < threshold -> sleep


def cole_kripke(activity, scale=_CK_SCALE, threshold=_CK_THRESHOLD):
    """Return float states (0=sleep, 1=wake, NaN=unscored).

    Existing array calls retain legacy scoring, including their historical
    zero-padding semantics. Arrays carry neither timestamps nor count provenance.
    Pass a DataFrame with Time and CK_activity (or 2-second CK_count) for corrected
    GGIR count-based scoring on a 60-second grid. For minute DataFrames the
    returned array matches the original row order; use score_sleep_wake for the
    full timestamped grid, especially with 2-second input.
    """
    if isinstance(activity, pd.DataFrame):
        states = score_sleep_wake(activity, scale=scale, threshold=threshold)
        times = pd.to_datetime(activity["Time"])
        return states.reindex(times).to_numpy()
    a       = np.asarray(activity, dtype=float)
    nanmask = np.isnan(a)
    a0      = np.nan_to_num(a, nan=0.0)
    n       = a0.shape[0]

    D = np.zeros(n, dtype=float)
    for w, off in zip(_CK_WEIGHTS, _CK_OFFSETS):
        shifted = np.zeros(n, dtype=float)
        if abs(off) >= n and off != 0:
            continue
        if off < 0:            # shifted[t] = a0[t + off]   (a past epoch)
            shifted[-off:] = a0[:n + off]
        elif off > 0:          # shifted[t] = a0[t + off]   (a future epoch)
            shifted[:n - off] = a0[off:]
        else:
            shifted = a0
        D += w * shifted
    D *= scale

    state = (D >= threshold).astype(float)   # 1 = wake, 0 = sleep
    state[nanmask] = np.nan
    return state


def _ggir_scores(activity, scale):
    """Literal GGIR 3.3-9 HASIB(ColeKripke1992) window/prefix/resize.

    GGIR create_rollfun_mat uses replicated endpoints and reversed columns;
    HASIB then prepends four wake scores and truncates to the input timeline.
    Preserve this actual alignment, even though it differs from the usual
    centred Cole-Kripke formula. Tests are generated by the unmodified R source.
    Input activity is minute count sum / 6, after g.sib.det's NA -> 0 step.
    """
    a = np.asarray(activity, dtype=float)
    if a.size == 0:
        return np.empty(0, dtype=float)
    a = np.nan_to_num(a, nan=0.0)
    windows = np.lib.stride_tricks.sliding_window_view(np.pad(a, (3, 3), mode="edge"), 7)
    scores = scale * (windows[:, ::-1] @ np.array([67, 74, 230, 76, 58, 54, 106]))
    # Equivalent to GGIR sleep=(PS < threshold), converted to this API's wake=1.
    scores = np.r_[np.full(4, 2.0), scores][:len(a)]
    return scores


def _ggir_cole_kripke(activity, scale, threshold):
    return (~(_ggir_scores(activity, scale) < threshold)).astype(float)


def score_sleep_wake(d, epoch_sec=60, scale=_CK_SCALE, threshold=_CK_THRESHOLD,
                     normalize_per_second=True):
    """One timestamp-aware entry point shared by SRI and sleep/wake plots.

    CK_activity: GGIR minute ZC count sum / 6, NOT SVM/60 or mean /30.
    CK_count: 2-second ZC counts; missing counts become zero as in g.sib.det.
    SVM only: exact legacy normalization/classification for independent upgrades.
    """
    if "CK_activity" in d or "CK_count" in d:
        if epoch_sec != 60:
            raise ValueError("Count-based Cole-Kripke scoring requires epoch_sec=60.")
        if "CK_activity" in d:
            activity = regular_grid(timed_series(d, "CK_activity"), 60)
        else:
            activity = counts_to_minutes(d)
        states = _ggir_cole_kripke(activity.to_numpy(), scale, threshold)
        return pd.Series(states, index=activity.index, name="wake")
    if d.attrs.get('count_method') == 'neishabouri':
        raise ValueError(
            "This file declares Neishabouri counts, but no validated "
            "Neishabouri-to-Cole-Kripke profile is configured. Refusing to "
            "silently fall back to SVM."
        )
    if "SVM" not in d:
        raise ValueError("Expected SVM, CK_activity or CK_count with Time.")
    # Preserve the established SVM fallback, including keep-first duplicates.
    s = (d[["Time", "SVM"]].dropna(subset=["Time"]).sort_values("Time")
         .set_index("Time")["SVM"])
    s = s[~s.index.duplicated(keep="first")]
    if s.empty:
        return pd.Series(dtype=float, index=pd.DatetimeIndex([]), name="wake")
    s = s.reindex(pd.date_range(s.index[0], s.index[-1], freq=f"{epoch_sec}s"))
    activity = s.to_numpy() / float(epoch_sec) if normalize_per_second else s.to_numpy()
    return pd.Series(cole_kripke(activity, scale=scale, threshold=threshold), index=s.index, name="wake")


# ── Epoch-by-day alignment ──────────────────────────────────────────────────────

def _dayByEpochMatrix(states, index, epoch_sec):
    # Reshape a flat, regularly-spaced sleep/wake series into a
    # [days x epochs-per-day] matrix aligned by *clock time of day*, so that
    # column j is always the same time of day on every row.
    #
    # Rows are reindexed to a complete run of consecutive calendar dates, so that
    # adjacent rows are guaranteed to be consecutive days (a fully-missing day
    # becomes an all-NaN row and is naturally excluded from the SRI comparison).
    #
    # Arguments:
    #   states    — 1-D array of 0/1/NaN states, one per epoch
    #   index     — DatetimeIndex aligned to `states` (regular epoch grid)
    #   epoch_sec — epoch length in seconds
    #
    # Returns: (mat, dates)
    #   mat   — numpy array [D x M], M = 86400 / epoch_sec, NaN where no data
    #   dates — DatetimeIndex of the D row dates (consecutive calendar days)
    M           = 86400 // epoch_sec
    sec_of_day  = index.hour * 3600 + index.minute * 60 + index.second
    epoch_of_day = (sec_of_day // epoch_sec).astype(int)     # 0 .. M-1
    dates        = index.normalize()                         # midnight of each day

    dfm = pd.DataFrame({'date': dates, 'eod': epoch_of_day, 'state': states})
    if len(index) == 0:
        return np.empty((0, M)), pd.DatetimeIndex([])
    mat_df = dfm.pivot_table(index='date', columns='eod',
                             values='state', aggfunc='first')

    # guarantee every epoch column exists, and every calendar day is a row
    full_dates = pd.date_range(index.min().normalize(), index.max().normalize(), freq='D')
    mat_df = mat_df.reindex(index=full_dates, columns=range(M))

    return mat_df.values, mat_df.index


# ── Public entry point ──────────────────────────────────────────────────────────

def compute_SRI(d, epoch_sec=60, scale=_CK_SCALE, threshold=_CK_THRESHOLD,
                min_pairs=1, normalize_per_second=True, verbose=False):
    """Compute SRI with the existing signature and result dictionary keys.

    Time + SVM uses the legacy SVM path. Optional CK_activity or CK_count selects
    the corrected counts path; normalize_per_second applies ONLY to SVM.
    The CLI/CSV loader discovers CK sidecars without caller changes.
    SVM is not a validated substitute for Motionlogger zero-crossing counts;
    neither scale robustness nor sleep validity is implied by this fallback.
    """
    if epoch_sec != 60:
        warnings.warn(f"compute_SRI: epoch_sec={epoch_sec}s but Cole-Kripke "
                      "weights are defined for 60-s epochs; results may be "
                      "unreliable.")

    scored_series = score_sleep_wake(d, epoch_sec, scale, threshold, normalize_per_second)
    states = scored_series.to_numpy()
    mat, dates = _dayByEpochMatrix(states, scored_series.index, epoch_sec)

    # ── 4. consecutive-day comparison ──────────────────────────────────────────
    today, tomorrow = mat[:-1], mat[1:]
    valid   = ~np.isnan(today) & ~np.isnan(tomorrow)
    matches = valid & (today == tomorrow)
    n_pairs = int(valid.sum())

    if n_pairs == 0 or n_pairs < min_pairs:
        sri = np.nan
    else:
        sri = 200.0 * matches.sum() / n_pairs - 100.0

    scored = states[~np.isnan(states)]
    pct_sleep = float((scored == 0).mean() * 100.0) if scored.size else np.nan

    result = {
        'SRI':                 sri,
        'n_days':              int(mat.shape[0]),
        'n_valid_epoch_pairs': n_pairs,
        'pct_epochs_sleep':    pct_sleep,
        'epoch_sec':           epoch_sec,
        'classifier':          'Cole-Kripke',
        'ck_scale':            scale,
        'ck_threshold':        threshold,
        'activity_normalization': ('GGIR ZC: minute sum/6; HASIB ColeKripke1992'
                                   if 'CK_activity' in d or 'CK_count' in d else
                                   'SVM_sum/epoch_sec (per-second)'
                                   if normalize_per_second else 'raw SVM_sum'),
        'states_matrix':       mat,
        'dates':               dates,
    }

    if verbose:
        sri_str = f"{sri:.2f}" if not np.isnan(sri) else "N/A"
        print(f"      SRI  = {sri_str}  "
              f"({mat.shape[0]} days, {n_pairs:,} epoch-pairs, "
              f"{pct_sleep:.1f}% epochs scored sleep)")

    return result
